const STORAGE_KEY = 'io-lang'
const en = { ...enExtra }
const listeners = new Set()
let current = 'en'

function captureEnglish() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n
    if (!(key in en)) en[key] = el.innerHTML.trim()
  })
  en['meta.title'] = document.title
  en['meta.description'] = document.querySelector('meta[name="description"]').content
}

function readStored() {
  try {
    return localStorage.getItem(STORAGE_KEY)
  } catch {
    return null
  }
}

function store(lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang)
  } catch {
    /* private mode — preference just won't persist */
  }
}

export function t(key) {
  const dict = current === 'fr' ? fr : en
  return dict[key] ?? en[key] ?? key
}

export const getLang = () => current

function apply(lang) {
  current = lang
  const dict = lang === 'fr' ? fr : en
  document.documentElement.lang = lang === 'fr' ? 'fr-CA' : 'en'
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const value = dict[el.dataset.i18n]
    if (value != null && el.innerHTML !== value) el.innerHTML = value
  })
  document.title = dict['meta.title']
  document.querySelector('meta[name="description"]').content = dict['meta.description']
  document.querySelectorAll('[data-lang]').forEach((btn) => {
    btn.setAttribute('aria-pressed', String(btn.dataset.lang === lang))
  })
  document.querySelector('.lang')?.setAttribute('data-active', lang)
}

/** Apply the preferred language immediately (before any text is split). */
export function initI18n() {
  captureEnglish()
  const stored = readStored()
  const browserFr = (navigator.language || '').toLowerCase().startsWith('fr')
  apply(stored === 'fr' || (!stored && browserFr) ? 'fr' : 'en')
}

export function onLangChange(fn) {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

/**
 * Switch language. `beforeApply`/`afterApply` hooks let the caller revert
 * split text and rebuild animations around the DOM swap.
 */
export function setLang(lang) {
  if (lang === current) return
  store(lang)
  listeners.forEach((fn) => fn('before', lang))
  apply(lang)
  listeners.forEach((fn) => fn('after', lang))
}
